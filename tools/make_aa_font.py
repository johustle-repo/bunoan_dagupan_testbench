"""Convert TrueType fonts into 4-bit anti-aliased bitmap fonts for the ESP32
ABS tester (esp32-abs-tester-28/AbsTester28/AaFonts.h).

Each glyph is rendered with FreeType (through Pillow) in greyscale and stored
as 4 bits of coverage per pixel, so AaGraphics.h can blend smooth edges onto
any background. Usage:

    python tools/make_aa_font.py <folder with the Barlow Semi Condensed .ttf files> <output AaFonts.h>

Font: Barlow Semi Condensed (https://github.com/jpt/barlow), SIL Open Font
License 1.1, Copyright 2017 The Barlow Project Authors.
"""
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ASCII = (0x20, 0x7E)
# name, weight file, pixel size (em), character range, comment.
FONTS = [
    ("aaSmall", "SemiBold", 11, ASCII, "units, legends and footnotes"),
    ("aaLabel", "SemiBold", 13, ASCII, "labels and status text"),
    ("aaPill", "Bold", 15, ASCII, "warning lights and status pill"),
    ("aaTitle", "Bold", 19, ASCII, "screen title"),
    ("aaValue", "Bold", 24, ASCII, "tile values and messages"),
    ("aaDial", "SemiBold", 14, (0x30, 0x39), "dial numbers"),
    ("aaBig", "Bold", 40, (0x2D, 0x39), "speed readout"),
]


def render_font(path, size, first, last):
    font = ImageFont.truetype(str(path), size)
    ascent, descent = font.getmetrics()
    glyphs, bitmap = [], bytearray()
    for code in range(first, last + 1):
        ch = chr(code)
        if code in (0x2E, 0x2F) and (first, last) == (0x2D, 0x39):
            glyphs.append((len(bitmap), 0, 0, 0, 0, 0))  # Unused in the readout font.
            continue
        advance = round(font.getlength(ch))
        pad = size
        img = Image.new("L", (advance + 2 * pad, ascent + descent + 2 * pad), 0)
        ImageDraw.Draw(img).text((pad, pad + ascent), ch, font=font, fill=255, anchor="ls")
        box = img.getbbox()
        if not box:
            glyphs.append((len(bitmap), 0, 0, advance, 0, 0))
            continue
        x0, y0, x1, y1 = box
        w, h = x1 - x0, y1 - y0
        offset = len(bitmap)
        for y in range(y0, y1):
            row = [min(15, (img.getpixel((x, y)) + 8) // 17) for x in range(x0, x1)]
            if len(row) % 2:
                row.append(0)
            bitmap.extend((row[i] << 4) | row[i + 1] for i in range(0, len(row), 2))
        glyphs.append((offset, w, h, advance, x0 - pad, y0 - pad - ascent))
    cap = -font.getbbox("H", anchor="ls")[1]
    return glyphs, bitmap, ascent + descent, cap


def main():
    src, out = Path(sys.argv[1]), Path(sys.argv[2])
    lines = [
        "#pragma once",
        "#include <Arduino.h>",
        "",
        "// Generated by tools/make_aa_font.py: 4-bit anti-aliased bitmap fonts.",
        "// Barlow Semi Condensed, SIL Open Font License 1.1,",
        "// Copyright 2017 The Barlow Project Authors (https://github.com/jpt/barlow).",
        "",
        "// Glyph: start of its bitmap (2 pixels per byte, high nibble first, each",
        "// row padded to a whole byte), size, advance and the offset of its",
        "// top-left corner from the pen position on the baseline.",
        "struct AaGlyph { uint16_t offset; uint8_t width, height, advance; int8_t xOffset, yOffset; };",
        "struct AaFont { const uint8_t* bitmap; const AaGlyph* glyphs; uint8_t first, last, lineHeight, capHeight; };",
        "",
    ]
    total = 0
    for name, weight, size, (first, last), comment in FONTS:
        glyphs, bitmap, line_height, cap = render_font(src / f"BarlowSemiCondensed-{weight}.ttf", size, first, last)
        total += len(bitmap) + 8 * len(glyphs)
        lines.append(f"// {name}: {weight} {size} px, {comment}.")
        lines.append(f"const uint8_t {name}Bitmap[] PROGMEM = {{")
        for i in range(0, len(bitmap), 24):
            lines.append("  " + ", ".join(f"0x{b:02X}" for b in bitmap[i:i + 24]) + ",")
        lines.append("};")
        lines.append(f"const AaGlyph {name}Glyphs[] PROGMEM = {{")
        for code, g in zip(range(first, last + 1), glyphs):
            label = chr(code) if chr(code) not in "\\'" else "\\" + chr(code)
            lines.append(f"  {{{g[0]}, {g[1]}, {g[2]}, {g[3]}, {g[4]}, {g[5]}}},  // '{label}'")
        lines.append("};")
        lines.append(f"const AaFont {name} = {{{name}Bitmap, {name}Glyphs, 0x{first:02X}, 0x{last:02X}, {line_height}, {cap}}};")
        lines.append("")
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"{out}: {total} bytes of font data")


if __name__ == "__main__":
    main()
